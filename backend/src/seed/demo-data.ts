import { TaskStatus } from '@prisma/client';

export type RoleKey = 'owner' | 'admin' | 'manager' | 'employee';

export interface Rand {
  int(min: number, max: number): number;
  pick<T>(items: readonly T[]): T;
}

export interface DemoClient {
  name: string;
  about: string;
  email?: string;
}

export interface DemoService {
  title: (about: string) => string;
  description: (about: string, r: Rand) => string;
}

export interface DemoStory {
  client: number;
  title: string;
  description: string;
  createdDaysAgo: number;
  dueInDays: number;
  assignee: RoleKey;
  notes: { daysAgo: number; by: RoleKey; text: string }[];
  tasks: { title: string; status: TaskStatus; dueInDays: number | null; to: RoleKey }[];
}

export interface DemoIndustry {
  slug: string;
  companyName: string;
  users: Record<RoleKey, string>;
  clients: DemoClient[];
  services: DemoService[];
  stories: DemoStory[];
  leadTasks: string[];
  standaloneTasks: string[];
}

